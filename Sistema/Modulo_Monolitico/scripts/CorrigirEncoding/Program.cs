// Pares (correto, corrompido) — aplicar corrompido -> correto
var pairs = new List<(string To, string From)>();
for (var i = 0; i < interrogacao.Length; i += 2)
    pairs.Add((interrogacao[i], interrogacao[i + 1]));

pairs.Sort((a, b) => b.From.Length.CompareTo(a.From.Length));

var sepLine = new Regex(@"^(\s*//)\s*\?{5,}\s*$", RegexOptions.Multiline);

int fixedCount = 0;

foreach (var file in Directory.GetFiles(root, "*.*", SearchOption.AllDirectories))
{
    if (!exts.Any(e => file.EndsWith(e, StringComparison.OrdinalIgnoreCase))) continue;
    if (skipDirs.Any(d => file.Contains(d, StringComparison.OrdinalIgnoreCase))) continue;

    try
    {
        var bytes = File.ReadAllBytes(file);
        var skip = bytes.Length >= 3 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF ? 3 : 0;
        var content = Encoding.UTF8.GetString(bytes, skip, bytes.Length - skip);
        var original = content;

        foreach (var kv in mojibake.OrderByDescending(x => x.Key.Length))
            content = content.Replace(kv.Key, kv.Value);

        foreach (var (to, from) in pairs)
            content = content.Replace(from, to);

        content = sepLine.Replace(content, "$1 ---");
        content = content.Replace("<span class=\"app-footer-sep\">?</span>", "<span class=\"app-footer-sep\">·</span>");
        content = content.Replace("In?cio", "Início");
        content = content.Replace(" 🚧 ", " ?? ");

        if (content != original)
        {
            File.WriteAllText(file, content, utf8Bom);
            Console.WriteLine("[OK] " + Path.GetRelativePath(root, file));
            fixedCount++;
        }
    }
    catch (IOException ex)
    {
        Console.WriteLine("[SKIP] " + Path.GetRelativePath(root, file) + " — " + ex.Message);
    }
}

Console.WriteLine("Corrigidos: " + fixedCount);
